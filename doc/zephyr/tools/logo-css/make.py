"""Writes css/zephyr-logo.css: the Nasdanika logo as a CSS variable, for the self-contained HTML.

The logo is downscaled to 96 pixels, twice its displayed size of 3rem at 16 pixels per rem, and
embedded as a data URI, so a book's HTML loads nothing. Run it from doc/zephyr after replacing
images/nasdanika-logo.png:

    python tools/logo-css/make.py

It needs Pillow.
"""
import base64
import io

from PIL import Image

SOURCE = "images/nasdanika-logo.png"
TARGET = "css/zephyr-logo.css"
SIZE = 96

image = Image.open(SOURCE).convert("RGBA").resize((SIZE, SIZE), Image.LANCZOS)
buffer = io.BytesIO()
image.save(buffer, format="PNG", optimize=True)
data = base64.b64encode(buffer.getvalue()).decode("ascii")

with open(TARGET, "w", encoding="utf-8", newline="\n") as css:
    css.write("/*\n")
    css.write(" * Nasdanika Zephyr Books: the Nasdanika logo, for the brand at the top left of the HTML.\n")
    css.write(" * Generated by tools/logo-css/make.py from images/nasdanika-logo.png; do not edit.\n")
    css.write(" */\n\n")
    css.write(":root {\n")
    css.write(f'\t--zb-logo: url("data:image/png;base64,{data}");\n')
    css.write("}\n")

print(f"{TARGET}: {len(data)} characters of base64")
